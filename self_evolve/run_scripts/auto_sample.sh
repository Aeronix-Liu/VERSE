#!/bin/bash
# Auto-sample the first SPAR step and first maze step of vilasr_full_selfevolve,
# then monitor for stability (10 consecutive steps without crash).
# Writes a markdown report to <ckpt>/sample_report.md.
# Designed to run in tmux so it survives SSH disconnect.
set -u

CKPT=/data/pengtianshuo/self_evolve/Xinran/checkpoints/vilasr_full_selfevolve
REPO=/data/pengtianshuo/self_evolve/Xinran/ViLaSR-self-evolve
EXPLOG="${CKPT}/experiment_log.jsonl"
LOGPATH_FILE="${REPO}/logs/latest_vilasr_full_selfevolve.logpath"
REPORT="${CKPT}/sample_report.md"
SCHEDULE="${REPO}/easy_r1/dataset/full_selfevolve_schedule.json"

# First maze step is step 6 (schedule[6] = maze_navigation, global_step is 1-indexed).
FIRST_MAZE_STEP=6
STABLE_TARGET=10

log() { echo "[$(date '+%H:%M:%S')] $*" | tee -a "${REPORT}.log"; }

{
  echo "# vilasr_full_selfevolve — auto sample report"
  echo
  echo "Generated by auto_sample.sh (tmux-persistent)."
  echo
  echo "## Schedule (first 10 steps)"
  python3 -c "
import json
s=json.load(open('${SCHEDULE}'))
for i in range(1,11):
    print(f'- step {i} -> {s[i % len(s)]}')
"
  echo
} > "${REPORT}"
log "Report initialized at ${REPORT}"

# ---------- Phase 1: wait for first maze step ----------
log "Phase 1: waiting for step ${FIRST_MAZE_STEP} (first maze) to complete..."
while true; do
  if [ -f "${EXPLOG}" ]; then
    STEPS=$(wc -l < "${EXPLOG}" 2>/dev/null || echo 0)
    if [ "${STEPS}" -ge "${FIRST_MAZE_STEP}" ]; then
      log "Step ${FIRST_MAZE_STEP} reached (steps_done=${STEPS})."
      break
    fi
    # crash check
    LOG=$(cat "${LOGPATH_FILE}" 2>/dev/null)
    if [ -f "${LOG}" ] && grep -aqE "torch.OutOfMemoryError|CUDA out of memory|exited rc=" "${LOG}" 2>/dev/null; then
      log "CRASH detected before reaching maze step. Aborting sampling."
      echo "## CRASH" >> "${REPORT}"
      grep -aE "OutOfMemory|Traceback|exited rc" "${LOG}" | tail -5 >> "${REPORT}"
      exit 1
    fi
  fi
  sleep 60
done

# ---------- Phase 2: sample step 1 (SPAR) and step 6 (maze) ----------
log "Phase 2: sampling step 1 (SPAR) and step ${FIRST_MAZE_STEP} (maze)..."
{
  echo "## Step 1 — first SPAR step"
  echo
  echo "### Round 1 (Proposer questions)"
  echo '```'
  python3 "${REPO}/run_scripts/show_samples.py" --ckpt "${CKPT}" --round1 --step 1 --n 4 2>&1
  echo '```'
  echo
  echo "### Round 2 (Solver rollouts — valid)"
  echo '```'
  python3 "${REPO}/run_scripts/show_samples.py" --ckpt "${CKPT}" --step 1 --n 3 --rollouts 2 2>&1
  echo '```'
  echo
  echo "### Round 2 (Solver rollouts — invalid, first 3)"
  echo '```'
  python3 "${REPO}/run_scripts/show_samples.py" --ckpt "${CKPT}" --invalid --step 1 --n 3 2>&1
  echo '```'
  echo
  echo "---"
  echo
  echo "## Step ${FIRST_MAZE_STEP} — first maze step"
  echo
  echo "### Round 1 (Proposer questions)"
  echo '```'
  python3 "${REPO}/run_scripts/show_samples.py" --ckpt "${CKPT}" --round1 --step ${FIRST_MAZE_STEP} --n 4 2>&1
  echo '```'
  echo
  echo "### Round 2 (Solver rollouts — valid)"
  echo '```'
  python3 "${REPO}/run_scripts/show_samples.py" --ckpt "${CKPT}" --step ${FIRST_MAZE_STEP} --n 3 --rollouts 2 2>&1
  echo '```'
  echo
  echo "### Round 2 (Solver rollouts — invalid, first 3)"
  echo '```'
  python3 "${REPO}/run_scripts/show_samples.py" --ckpt "${CKPT}" --invalid --step ${FIRST_MAZE_STEP} --n 3 2>&1
  echo '```'
  echo
} >> "${REPORT}" 2>&1
log "Sampling written to ${REPORT}"

# ---------- Phase 3: monitor for stability ----------
log "Phase 3: monitoring for stability (${STABLE_TARGET} steps) or crash..."
LAST=0
while true; do
  sleep 90
  STEPS=$(wc -l < "${EXPLOG}" 2>/dev/null || echo 0)
  LOG=$(cat "${LOGPATH_FILE}" 2>/dev/null)
  if [ -f "${LOG}" ] && grep -aqE "torch.OutOfMemoryError|CUDA out of memory|exited rc=|Traceback" "${LOG}" 2>/dev/null; then
    log "CRASH detected at steps_done=${STEPS}."
    {
      echo "## CRASH at step ${STEPS}"
      echo '```'
      grep -aE "OutOfMemory|Traceback|exited rc" "${LOG}" | tail -5
      echo '```'
    } >> "${REPORT}"
    exit 1
  fi
  if [ "${STEPS}" != "${LAST}" ]; then
    log "progress: steps_done=${STEPS}"
    LAST=${STEPS}
  fi
  if [ "${STEPS}" -ge "${STABLE_TARGET}" ]; then
    log "STABLE: reached ${STEPS} steps without crash."
    {
      echo "## Stability report"
      echo
      echo "Reached **${STEPS} steps** without crash — training is stable."
      echo
      echo "### Per-step metrics"
      echo '```'
      python3 -c "
import json
rows=[json.loads(l) for l in open('${EXPLOG}')]
for r in rows:
    step=r.get('step') or r.get('global_step')
    sched=r.get('round1_scheduler',{}); sel=sched.get('selected_count',{}) if isinstance(sched,dict) else {}
    ttype=','.join(sel.keys()) if sel else r.get('task_type','?')
    r1q=r.get('reward_round1',{}).get('quality')
    r2=r.get('round2',{}); inv=r2.get('invalid_ratio'); uniq=r2.get('unique_question_count_before_answer')
    rr2=r.get('reward_round2',{}); ov=rr2.get('overall'); acc=rr2.get('accuracy')
    print(f'  step={step:>3} task={ttype:34s} r1q={r1q} r2ov={ov} r2acc={acc} r2inv={inv} uniq={uniq}')
"
      echo '```'
    } >> "${REPORT}"
    log "Stability report appended. DONE."
    exit 0
  fi
done
